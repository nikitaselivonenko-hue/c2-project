// cp866ToUTF8 конвертирует строку из CP866 в UTF-8.
func cp866ToUTF8(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < 0x80 {
			b.WriteByte(c)
			continue
		}
		if r, ok := cp866Table[c]; ok {
			b.WriteRune(r)
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}